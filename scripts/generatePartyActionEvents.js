// Writes lib/Game/Heap/PartyActionEvents.js: the ordered heap events of a party member's Attack and item, by action tag (ActionFootprints
// tags: m<member>A0t7, m<member>I<slot>t<target>), from Suikoden-Bizhawk-HUD enemy_profiles/vfx_effects/party_action_event_lists_v1.json
// (brief item 13a, recorded in rounds 1 and 3 of the party L-fire-slow, 2 seeds). The list is the same in both seeds and both rounds
// (checked here). Event format of EnemyMoveEvents: a positive number is an allocation of that many bytes, -k the free of the k-th one.
// usage: node scripts/generatePartyActionEvents.js [<vfx_effects dir>]    then: npx prettier --write lib/Game/Heap/PartyActionEvents.js
import fs from 'node:fs';

const DIR =
  process.argv[2] ?? '/home/alex/Projects/Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects';
const lists = JSON.parse(fs.readFileSync(`${DIR}/party_action_event_lists_v1.json`, 'utf8'));

/** @param {{ kind: string, size: number, frees_own_alloc?: number | null }[]} extra */
const toEvents = (extra) =>
  extra.map((e) => (e.kind === 'a' ? e.size : -(Number(e.frees_own_alloc) + 1)));

/** @type {Record<string, number[]>} */
const out = {};
for (const [name, seeds] of Object.entries(lists)) {
  const m = /^r([13])(m\d[AI]\d?t\d)$/.exec(name);
  if (!m) continue; // runes, the Unite and the death cases are not here
  const tag = m[2];
  const variants = Object.values(/** @type {Record<string, any>} */ (seeds)).map((r) =>
    toEvents(r.extra),
  );
  if (variants.some((v) => JSON.stringify(v) !== JSON.stringify(variants[0])))
    throw new Error(`${name}: the two seeds differ`);
  const events = variants[0];
  if (out[tag] && JSON.stringify(out[tag]) !== JSON.stringify(events))
    throw new Error(`${tag}: rounds 1 and 3 differ`);
  // a free of a block that existed before the action has no own allocation: the agent's lists have none of those for these tags
  if (events.some((e) => Number.isNaN(e)))
    throw new Error(`${name}: a free without an own allocation`);
  out[tag] = events;
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  new URL('../lib/Game/Heap/PartyActionEvents.js', import.meta.url),
  `// Generated by scripts/generatePartyActionEvents.js from Suikoden-Bizhawk-HUD enemy_profiles/vfx_effects (v1.0 disc). Do not edit.
/**
 * The ordered heap events of a party member's Attack or item, by action tag (the HeapSpellEvents format: a positive number is an
 * allocation, -k the free of the k-th allocation): the hit effect's (52, 80, 80) freed 19-21 ticks later, the Mega medicine's 368 and eight
 * sets, a spell-less empty item slot's nothing. Recorded in the party L-fire-slow, rounds 1 and 3.
 * @type {Record<string, number[]>}
 */
export const PARTY_ACTION_EVENTS = ${JSON.stringify(sorted)};
`,
);
