// Writes lib/Game/Heap/Sqrt0Table.js: the game's square-root table (the effects' `sqrt0`: 16-bit entries indexed by the normalised
// argument), read from Suikoden-Bizhawk-HUD/lib/Magic.lua (`Sqrt0TableHex`). usage: node scripts/generateSqrt0Table.js [<Magic.lua>]
// then: npx prettier --write lib/Game/Heap/Sqrt0Table.js
import fs from 'node:fs';

const SOURCE = process.argv[2] ?? '/home/alex/Projects/Suikoden-Bizhawk-HUD/lib/Magic.lua';
const hex = /Sqrt0TableHex = "([0-9a-f]+)"/.exec(fs.readFileSync(SOURCE, 'utf8'))?.[1];
if (!hex) throw new Error('Sqrt0TableHex not found');
const bytes = Buffer.from(hex, 'hex');
const table = Array.from({ length: bytes.length / 2 }, (_, i) => bytes.readInt16LE(2 * i));
fs.writeFileSync(
  new URL('../lib/Game/Heap/Sqrt0Table.js', import.meta.url),
  `// Generated by scripts/generateSqrt0Table.js from Suikoden-Bizhawk-HUD/lib/Magic.lua. Do not edit.
/** The game's square-root table: signed 16-bit entries indexed by the normalised argument (sqrt0) */
export const SQRT0_TABLE = ${JSON.stringify(table)};
`,
);
console.log(table.length, 'entries');
