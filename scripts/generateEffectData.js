// Generates lib/Game/Heap/Engine/EffectData.js: the bytes of the game files the battle effect-script engine reads (the party
// characters' files up to their resource tables, the battle.bin effect tables, main.exe's script tables), from the disc extraction.
// usage: SUIKODEN_V10="/path/to/Suikoden Files v1.0/" node scripts/generateEffectData.js
import fs from 'node:fs';
import path from 'node:path';

const DISC = process.env.SUIKODEN_V10 ?? '/mnt/Shared/ISOs/Suikoden/Suikoden Files v1.0/';
const read = (/** @type {string} */ file) => fs.readFileSync(path.join(DISC, file));
const b64 = (/** @type {Uint8Array} */ b) => Buffer.from(b).toString('base64');

// main.exe is loaded at 0x800c0800 from file offset 0x800: the script tables and the scripts the hit effects use lie at 0x80170000..
const MAIN_FROM = 0x80170000;
const MAIN_TO = 0x80171400;
const main = read('main.exe').subarray(
  0x800 + (MAIN_FROM - 0x800c0800),
  0x800 + (MAIN_TO - 0x800c0800),
);
// battle.bin at 0x800aa000: the effect sprite resource table (entries, frame lists, frames)
const BATTLE_BYTES = 0x1000;
const battle = read('data/00_init/battle.bin').subarray(0, BATTLE_BYTES);

/** the party characters' files: everything the engine reads (the header, the 12 scripts, the resource table) lies below the pixel data */
const dir = path.join(DISC, 'data/04_play');
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.bin'))
  .sort();
/** @type {string[]} */
const characters = [];
for (const f of files) {
  const d = fs.readFileSync(path.join(dir, f));
  const res = d.readUInt32LE(0x24);
  const end = res + 0x40;
  characters.push(
    `  ${JSON.stringify(f.replace('.bin', ''))}: { rosterId: ${d[0]}, bytes: '${b64(d.subarray(0, end))}' },`,
  );
}
// Crystal Core's area overlay (09_area.f/vf2.bin at 0x80010000): its attack child's script and its sprite resource table (the target's
// hit pose is set from it). Other enemies' records: not extracted yet.
const OVERLAY_BASE = 0x80010000;
const vf2 = read('data/09_area.f/vf2.bin');
const overlayRegions = [
  [0x80054b00, 0x80054d00],
  [0x8006b000, 0x8006b800],
].map(
  ([from, to]) =>
    `{ base: ${from}, bytes: '${b64(vf2.subarray(from - OVERLAY_BASE, to - OVERLAY_BASE))}' }`,
);
const out = `// Generated by scripts/generateEffectData.js from the disc files (NTSC-U v1.0): the bytes of the game files the battle effect-script
// engine reads. Do not edit.

/** main.exe at 0x80170000..: the hit-effect script tables and scripts */
export const MAIN_EXE = { base: ${MAIN_FROM}, bytes: '${b64(main)}' };

/** battle.bin at 0x800aa000: the generic effect sprite resource table */
export const BATTLE_BIN = { base: 0x800aa000, bytes: '${b64(battle)}' };

/** Crystal Core's overlay: the parts the engine reads */
export const CRYSTAL_CORE_OVERLAY = [
  ${overlayRegions.join(',\n  ')},
];

/** the party characters' files (data/04_play/<code>.bin), as stored: the file-relative pointers are not yet made absolute */
export const CHARACTER_FILES = /** @type {Record<string, { rosterId: number, bytes: string }>} */ ({
${characters.join('\n')}
});
`;
fs.writeFileSync(new URL('../lib/Game/Heap/Engine/EffectData.js', import.meta.url), out);
console.log('written', out.length, 'bytes,', files.length, 'characters');
