// Writes lib/Game/Heap/HitEffectTables.js (libgte sin/cos, the Attack's sine table, camera presets, member positions) and
// test/fixtures/heap/tables/hit_effect_trace.json (per seed: camera class, target slot, the 12 resources' header screen positions per frame)
// from Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects. usage: node scripts/generateHitEffectTables.js [<vfx_effects dir>]
// then: npx prettier --write lib/Game/Heap/HitEffectTables.js test/fixtures/heap/tables/hit_effect_trace.json
import fs from 'node:fs';

const DIR =
  process.argv[2] ?? '/home/alex/Projects/Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects';
const read = (/** @type {string} */ f) => JSON.parse(fs.readFileSync(`${DIR}/${f}`, 'utf8'));

const gte = read('libgte_rsin_rcos_v10.json');
const quarter = read('attack_script_and_trig_v10.json').sin_quarter_table_0x8017ac3c_s16x1024;
const presets = read('battle_camera_presets_v10.json');
const members = read('party_member_positions_v10.json').members;
const hitPoints = read('atk_hit_point_table_v10.json').by_character_id;

/** @param {string} hex little-endian bytes -> 12 signed words */
const words = (hex) =>
  Array.from({ length: 12 }, (_, i) => Buffer.from(hex, 'hex').readInt32LE(i * 4));

const cameras = [0, 1, 2].map((c) => words(presets[c].bytes));
const memberTable = Object.fromEntries(
  Object.entries(members).map(([k, m]) => [k, [m.x, m.y, m.z]]),
);

const hitPointTable = Object.fromEntries(
  Object.entries(hitPoints).map(([id, c]) => [id, [c.a78, c.a79]]),
);

const out = `// Generated by scripts/generateHitEffectTables.js from Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects (v1.0 disc). Do not edit.
/** libgte sin / cos tables (4096 = one turn, 4096 = 1.0) */
export const GTE_SIN = ${JSON.stringify(gte.sin)};
export const GTE_COS = ${JSON.stringify(gte.cos)};
/** the Attack's quarter sine table (1024 s16) */
export const SIN_QUARTER = ${JSON.stringify(quarter)};
/** the three camera class presets: 12 u32 words: look, rotation, translation, scale (value >> 12 is used) */
export const CAMERA_PRESETS = ${JSON.stringify(cameras)};
/** party member positions by battle slot 1..6: x, y, z shorts (the record is ((x + 0x80) << 12, y << 12, z << 12)) */
export const MEMBER_POSITIONS = ${JSON.stringify(memberTable)};
/** the hit-spark child's hit point (a78, a79) by character id: the owner's current sprite list b6 - b4, b7 - b5 (a table of the character's own sprite data) */
export const HIT_POINTS = ${JSON.stringify(hitPointTable)};
`;
fs.writeFileSync(new URL('../lib/Game/Heap/HitEffectTables.js', import.meta.url), out);

// the trace fixture
const seeds = ['9e3779b1', 'daa66d13', '78dde6c4', '17156075', '3c6ef362', 'b54cda26'];
/** @type {Record<string, unknown>} */
const trace = {};
for (const seed of seeds) {
  const lines = fs
    .readFileSync(`${DIR}/header_trace/header_L-fire-slow_${seed}.txt`, 'utf8')
    .split('\n');
  const camera = Number(/camera class (\d)/.exec(lines[0])?.[1]);
  /** @type {Map<number, number[]>} resource -> per frame [frame, sx, sy] */
  const series = new Map();
  let frame = 0;
  /** @type {Map<number, number>} */
  const word2 = new Map();
  /** @type {Map<number, number>} */
  const word3 = new Map();
  for (const line of lines) {
    const f = /^frame (\d+)/.exec(line);
    if (f) {
      frame = Number(f[1]);
      continue;
    }
    const m = /^\s+blk (\d+) size 52 word (\d+) .*-> ([0-9a-f]{8})$/.exec(line);
    if (!m || Number(m[1]) % 3 !== 0 || Number(m[1]) >= 36) continue;
    const r = Number(m[1]) / 3;
    const v = parseInt(m[3], 16);
    if (m[2] === '2') {
      word2.set(r, v);
      const s16 = (/** @type {number} */ x) => (x << 16) >> 16;
      const entry = series.get(r) ?? [];
      entry.push(frame, s16(v & 0xffff) >> 3, s16(v >>> 16) >> 3);
      series.set(r, entry);
    }
    if (m[2] === '3') word3.set(r, v);
  }
  trace[seed] = {
    camera,
    resources: Object.fromEntries([...series].map(([r, a]) => [r, a])),
  };
}
// the 24 packet addresses in allocation order (the same in every run of the recorded party)
const addresses = fs
  .readFileSync(`${DIR}/header_trace/header_L-fire-slow_9e3779b1.txt`, 'utf8')
  .split('\n')
  .flatMap((line) => {
    const m = /^\s+blk \d+ size 40 word 0 \((\w+),/.exec(line);
    return m ? [parseInt(m[1], 16)] : [];
  });
// the 12 launch resources' header addresses
const headers = fs
  .readFileSync(`${DIR}/header_trace/header_L-fire-slow_9e3779b1.txt`, 'utf8')
  .split('\n')
  .flatMap((line) => {
    const m = /^\s+blk (\d+) size 52 word 0 \((\w+),/.exec(line);
    return m && Number(m[1]) < 36 ? [parseInt(m[2], 16)] : [];
  });
fs.writeFileSync(
  new URL('../test/fixtures/heap/tables/hit_effect_trace.json', import.meta.url),
  JSON.stringify({ addresses, headers, seeds: trace }),
);
