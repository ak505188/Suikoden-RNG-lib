// Writes lib/Game/Heap/OtherSpellEvents.js: the ordered heap events of the rune spells that are not one of the five particle spells, by
// spell name, from Suikoden-Bizhawk-HUD enemy_profiles/vfx_effects/party_action_event_lists_v2.json (`spells.<id>.signed_r1_9e3779b1`: the
// spell's own allocations and frees in order, +size for an allocation and -n for the free of the n-th allocation, checked against the
// 510 recordings: no event lost). The list is the same for every tag, target, seed and round of a spell.
// usage: node scripts/generateOtherSpellEvents.js [<vfx_effects dir>]    then: npx prettier --write lib/Game/Heap/OtherSpellEvents.js
import fs from 'node:fs';

const DIR =
  process.argv[2] ?? '/home/alex/Projects/Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects';
const lists = JSON.parse(fs.readFileSync(`${DIR}/party_action_event_lists_v2.json`, 'utf8'));
const FIVE = ['Flaming Arrow', 'Explosion', 'Thor', 'Black Shadow', 'Hell'];
// the library's spell names where the recordings' differ
const NAME = /** @type {Record<string, string>} */ ({ Judgment: 'Judgement' });

/** @type {Record<string, number[]>} */
const out = {};
for (const {
  spell,
  signed_r1_9e3779b1: events,
  signed_identical_all_tags_seeds: same,
} of Object.values(
  /** @type {Record<string, { spell: string, signed_r1_9e3779b1: number[], signed_identical_all_tags_seeds: boolean }>} */ (
    lists.spells
  ),
)) {
  if (FIVE.includes(spell)) continue;
  if (!same) throw new Error(`${spell}: the lists differ between tags or seeds`);
  // every allocation is freed once, a free names an earlier allocation
  let allocs = 0;
  const freed = new Set();
  for (const e of events) {
    if (e > 0) allocs++;
    else if (-e > allocs || freed.has(-e)) throw new Error(`${spell}: a bad free ${e}`);
    else freed.add(-e);
  }
  if (freed.size !== allocs) throw new Error(`${spell}: ${allocs - freed.size} blocks never freed`);
  out[NAME[spell] ?? spell] = events;
}
fs.writeFileSync(
  new URL('../lib/Game/Heap/OtherSpellEvents.js', import.meta.url),
  `// Generated by scripts/generateOtherSpellEvents.js from Suikoden-Bizhawk-HUD enemy_profiles/vfx_effects (v1.0 disc). Do not edit.
/**
 * The ordered heap events of the rune spells that are not one of the five particle spells, by spell name (the HeapSpellEvents format: a
 * positive number is an allocation, -k the free of the k-th allocation; the first is the 16384-byte loader buffer). The same for every
 * target, round and seed. Recorded in the party L-fire-slow, rounds 1 and 3, the cast alone (not the post-cast blocks of the next action).
 * @type {Record<string, number[]>}
 */
export const OTHER_SPELL_EVENTS = ${JSON.stringify(out)};
`,
);
