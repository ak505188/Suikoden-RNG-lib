// Writes lib/Game/Heap/SpecialLoaderWords.js: the words of the Special's 16384-byte loader buffer (file data, seed- and party-independent)
// that the Special's own blocks leave unwritten and so keep as stale words, by offset from the buffer's start. Sources: the stale words of
// the wrapper objects (Suikoden-Bizhawk-HUD enemy_profiles/vfx_effects/sobj_stale_words_slow_v10.json, source = loader_buffer) and the
// pad bytes of system 2's G4 records (read from the busyend dump of test/fixtures/heap: the buffer's last 0x3d8 bytes).
// usage: node scripts/generateSpecialLoaderWords.js [<vfx_effects dir>]   then: npx prettier --write lib/Game/Heap/SpecialLoaderWords.js
import fs from 'node:fs';

const DIR =
  process.argv[2] ?? '/home/alex/Projects/Suikoden-Bizhawk-HUD/enemy_profiles/vfx_effects';
const LOADER = 0x8018b890;
const stale = JSON.parse(fs.readFileSync(`${DIR}/sobj_stale_words_slow_v10.json`, 'utf8')).words;

/** @type {Map<number, number>} offset (of the word) -> value, masked to the bytes the stale source covers */
const words = new Map();
for (const w of stale) {
  if (w.source !== 'loader_buffer') continue;
  const addr = parseInt(w.addr, 16);
  const base = addr - (addr % 4);
  const mask = parseInt(w.mask, 16) >>> 0;
  const value = (parseInt(w.final, 16) & mask) >>> 0;
  // two stale halves of one word are two entries: merge them
  words.set(base - LOADER, ((words.get(base - LOADER) ?? 0) | value) >>> 0);
}

// system 2's G4 pad bytes (top byte of words 3, 5 and 7 of each of the 10 records of both buffers), from the arena at the free
const dump = fs.readFileSync(
  new URL(
    '../test/fixtures/heap/crystal_core_L-fire-slow_inround_special_17156075_busyend.bin',
    import.meta.url,
  ),
);
for (const buffer of [0x8018f728, 0x8018f538])
  for (let i = 0; i < 10; i++)
    for (const w of [3, 5, 7]) {
      const addr = buffer + 36 * i + 4 * w;
      if (addr < LOADER || addr >= LOADER + 16384) continue;
      const base = addr - LOADER;
      const pad = dump.readUInt32LE(addr - 0x80182000) & 0xff000000;
      words.set(base, ((words.get(base) ?? 0) | pad) >>> 0);
    }

const sorted = [...words].sort((a, b) => a[0] - b[0]);
fs.writeFileSync(
  new URL('../lib/Game/Heap/SpecialLoaderWords.js', import.meta.url),
  `// Generated by scripts/generateSpecialLoaderWords.js. Do not edit.
/**
 * The bytes of the Special's 16384-byte loader buffer (the file the loader reads at the effect's start: constant for every seed and party)
 * that the effect's own blocks never write, so they stay as the stale words they were: [offset from the buffer, value (only the covered
 * bytes are set)]. The buffer is allocated at 0x8018b890 in every recorded fight.
 * @type {[number, number][]}
 */
export const SPECIAL_LOADER_WORDS = ${JSON.stringify(sorted)};
`,
);
